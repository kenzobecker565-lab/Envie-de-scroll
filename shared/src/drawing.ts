export function drawingSuggestions(duration:Duration,style:DrawingStyle,done:readonly string[],recent:readonly string[]=[],random=Math.random){
 const pool=drawingActivitiesFor(duration,style).map(a=>({a,r:random()})).sort((x,y)=>Number(done.includes(x.a.id))-Number(done.includes(y.a.id))||Number(recent.includes(x.a.id))-Number(recent.includes(y.a.id))||x.r-y.r).map(x=>x.a)
 const chosen:DrawingActivity[]=[]
 while(chosen.length<3&&pool.length){const first=pool[0]!;let i=pool.findIndex(a=>done.includes(a.id)===done.includes(first.id)&&recent.includes(a.id)===recent.includes(first.id)&&!chosen.some(c=>c.family===a.family));if(i<0)i=0;chosen.push(pool.splice(i,1)[0]!)}return chosen
}
